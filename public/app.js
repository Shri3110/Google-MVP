// DOM Elements
const searchInput = document.getElementById('searchInput');
const searchBtn = document.getElementById('searchBtn');
const photoGrid = document.getElementById('photoGrid');
const skeletonGrid = document.getElementById('skeletonGrid');
const emptyState = document.getElementById('emptyState');
const galleryDate = document.getElementById('galleryDate');

// Disambiguation UI
const askPhotosCard = document.getElementById('askPhotosCard');
const cardContent = document.getElementById('cardContent');
const cardContext = document.getElementById('cardContext');
const cardQuestion = document.getElementById('cardQuestion');
const cardChips = document.getElementById('cardChips');
const cardLoading = document.getElementById('cardLoading');
const cardConfirmation = document.getElementById('cardConfirmation');
const cardFailed = document.getElementById('cardFailed');

// Refined Header
const refinedHeader = document.getElementById('refinedHeader');
const resultCountText = document.getElementById('resultCountText');
const refinementPill = document.getElementById('refinementPill');

// State
let currentQuery = '';
let currentRound = 1;
let collectedClues = [];
let currentPrompts = null;

// Dynamic Mock Photos Removed: Now using real backend retrieval array.

// Event Listeners
searchBtn.addEventListener('click', handleSearch);
searchInput.addEventListener('keypress', (e) => {
    if (e.key === 'Enter') handleSearch();
});

// Initialize Default Camera Roll on Load
document.addEventListener('DOMContentLoaded', () => {
    emptyState.classList.add('hidden');
    galleryDate.classList.remove('hidden');
    
    // Generate 50 completely random photos for the initial "messy" camera roll
    const cameraRoll = [];
    for (let i = 0; i < 50; i++) {
        cameraRoll.push({
            url: `https://picsum.photos/seed/initial${i}/300/300`,
            desc: `Camera roll photo ${i}`
        });
    }
    renderPhotos(cameraRoll);
});

// Core Functions
async function handleSearch() {
    const query = searchInput.value.trim().toLowerCase();
    if (!query) return;

    // Reset state
    currentQuery = query;
    currentRound = 1;
    collectedClues = [];
    currentPrompts = null;

    hideAll();
    showSkeletons();

    try {
        const response = await fetch('/api/search', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ query: currentQuery })
        });
        const data = await response.json();

        hideSkeletons();

        if (data.status === 'failure') {
            currentPrompts = data.prompts;
            
            // Render the initial unrefined grid below the card
            galleryDate.classList.remove('hidden');
            renderPhotos(data.results);

            // STATE 3: Trigger Ask Photos Back card above it
            triggerAskPhotosBack();
        } else {
            // STATE 2: Good Result
            galleryDate.classList.remove('hidden');
            renderPhotos(data.results);
        }
    } catch (err) {
        console.error(err);
        hideSkeletons();
    }
}

function triggerAskPhotosBack() {
    askPhotosCard.classList.remove('hidden');
    cardContent.classList.remove('hidden');
    cardLoading.classList.add('hidden');
    cardFailed.classList.add('hidden');
    
    if (!currentPrompts || currentPrompts.length === 0) {
        showFailedClarification();
        return;
    }

    // Pick the top prompt generated by the LLM
    const activePrompt = currentPrompts[0];
    
    cardContext.textContent = currentRound === 1 ? 'I need some more details to find exactly what you are looking for.' : 'I found fewer photos, but there are still quite a few possibilities.';
    cardQuestion.textContent = activePrompt.prompt;
    
    // Render LLM generated choice chips
    cardChips.innerHTML = '';
    if (activePrompt.options) {
        activePrompt.options.forEach(chipText => {
            const btn = document.createElement('button');
            btn.className = 'choice-chip';
            btn.textContent = chipText;
            btn.addEventListener('click', () => handleClueSelection(chipText, activePrompt.type));
            cardChips.appendChild(btn);
        });
    }
}

async function handleClueSelection(clueText, clueType) {
    collectedClues.push(clueText);
    
    // STATE 4: User provides clue (Loading state in card)
    cardContent.classList.add('hidden');
    cardLoading.classList.remove('hidden');
    cardConfirmation.textContent = `Got it — ${clueText.toLowerCase()}.`;

    try {
        const response = await fetch('/api/search', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ 
                query: currentQuery,
                clue: { type: clueType, value: clueText }
            })
        });
        const data = await response.json();
        
        if (data.status === 'success') {
            // Pass the LLM synthesized query to the refined results
            showRefinedResults(data.query, data.results);
        } else {
            showFailedClarification();
        }
    } catch (err) {
        console.error(err);
        showFailedClarification();
    }
}

function showRefinedResults(synthesizedQuery, matchedPhotos) {
    askPhotosCard.classList.add('hidden');
    refinedHeader.classList.remove('hidden');
    
    // Hide the memory chips and date titles for a refined search view, but KEEP the grid section visible!
    const memoriesRow = document.querySelector('.memories-row');
    const monthTitle = document.querySelector('.month-title');
    const dateSubtitle = document.querySelector('.date-subtitle');
    if (memoriesRow) memoriesRow.classList.add('hidden');
    if (monthTitle) monthTitle.classList.add('hidden');
    if (dateSubtitle) dateSubtitle.classList.add('hidden');
    
    // Render the actual retrieved photos from the backend!
    resultCountText.textContent = `${matchedPhotos.length} photos found`;
    refinementPill.textContent = `Refined using AI: "${synthesizedQuery}"`;
    
    renderPhotos(matchedPhotos);
}

function showFailedClarification() {
    cardContent.classList.add('hidden');
    cardLoading.classList.add('hidden');
    cardFailed.classList.remove('hidden');
}

// Helpers
function renderPhotos(photos) {
    photoGrid.innerHTML = '';
    photoGrid.classList.remove('hidden');
    
    photos.forEach(photo => {
        const div = document.createElement('div');
        div.className = 'photo-card';
        div.innerHTML = `<img src="${photo.url}" alt="${photo.desc}">`;
        photoGrid.appendChild(div);
    });
}

function showSkeletons() {
    skeletonGrid.classList.remove('hidden');
}

function hideSkeletons() {
    skeletonGrid.classList.add('hidden');
}

function hideAll() {
    emptyState.classList.add('hidden'); // Never show empty state anymore
    photoGrid.classList.add('hidden');
    askPhotosCard.classList.add('hidden');
    refinedHeader.classList.add('hidden');
    galleryDate.classList.add('hidden');
    
    // Reset the visibility of memory chips and dates for new searches
    const memoriesRow = document.querySelector('.memories-row');
    const monthTitle = document.querySelector('.month-title');
    const dateSubtitle = document.querySelector('.date-subtitle');
    if (memoriesRow) memoriesRow.classList.remove('hidden');
    if (monthTitle) monthTitle.classList.remove('hidden');
    if (dateSubtitle) dateSubtitle.classList.remove('hidden');
}
